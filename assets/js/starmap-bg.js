/* ============================================================
   星图页专用背景参数
   ------------------------------------------------------------
   星图页的背景是一张「坐标纸」：直角网格 + 网格交点，星系落在交点上。
   与全站六边形背景同一套配色（暗紫 / 冷灰 / 金色点缀），但结构完全不同，
   避免与星图的星点、光晕、连线互相干扰。

   · GRID_STYLE = 'coord'：换成直角坐标网格，小格边长 = 视口高 / COORD_N
     坐标系原点 (0, 0) 初始位于视口正中，就是维斯佩拉星系所在的位置
   · 三级刻度：小坐标（每 1 小格）/ 中坐标（每 5 小格）/ 大坐标（每 25 小格）
     显隐跟左下角滑块走：滑轨三等分，每过 1/3 显示更小一级
     （左 1/3 只有大坐标 → 中 1/3 加中坐标 → 右 1/3 再加小坐标）
   · 网格线整体压暗，三级之间靠颜色与线宽区分
   · 星空稀疏且静止，作为底噪
   · 极光只留一点点，且完全静止
   · 关闭鼠标激活区：星图自己的悬停/选中反馈才是主体

   必须在 assets/js/background.js 之前加载。
   ============================================================ */
/* 滑块位置 → 比例尺：与 starmap.js 的 zoomFromSliderPos 用同一套分段等比映射
   （0..0.5 从最小到默认，0.5..1 从默认到最大，于是默认比例尺恒在滑轨正中）。
   写在这里是为了在配置里直接算出「三等分处」对应的比例尺。 */
function sssZoomAtSliderPos(t) {
  var MIN = 0.25, DEF = 0.5, MAX = 1.45;   // 与下面 ZOOM_MIN / ZOOM_DEFAULT / ZOOM_MAX 一致
  if (t <= 0.5) return MIN * Math.pow(DEF / MIN, t * 2);
  return DEF * Math.pow(MAX / DEF, (t - 0.5) * 2);
}

window.SSS_BG = {
  /* --- 网格：坐标纸（三级刻度） --- */
  GRID_STYLE: 'coord',
  /* 纵向小格数 34 → 基准小格 = 视口高 / 34 ≈ 21px（宽 1400 的窗口下约 12px/小格）。
     初始比例尺 0.5：可见约 68 小格高（1384×805 下竖直 68 格、水平约 117 格）。

     三级刻度按滑块三等分显现（比例尺换算：1/3 → 0.397，2/3 → 0.713）：
       左 1/3：0.25 ~ 0.397   只有大坐标
       中 1/3：0.397 ~ 0.713  大坐标 + 中坐标（默认比例尺 0.5 就在这一段）
       右 1/3：0.713 ~ 1.45   大坐标 + 中坐标 + 小坐标 */
  COORD_N: 34,
  COORD_MEDIUM_STEP: 5,      // 中坐标：每 5 个小格
  COORD_MAJOR_STEP: 25,      // 大坐标：每 25 个小格
  /* 显隐判据：按比例尺档位（背景引擎里的 COORD_LEVEL_BY_ZOOM） */
  COORD_LEVEL_BY_ZOOM: true,
  COORD_MEDIUM_FROM_ZOOM: sssZoomAtSliderPos(1 / 3),   // ≈ 0.397
  COORD_MINOR_FROM_ZOOM: sssZoomAtSliderPos(2 / 3),    // ≈ 0.713
  COORD_MINOR: '#2b2b40',    // 小坐标：最细最暗
  COORD_MEDIUM_C: '#3b3b58', // 中坐标
  COORD_MAJOR_C: '#565679',  // 大坐标
  COORD_AXIS: '#6a6a92',     // 坐标轴：过原点 (0,0)，也就是穿过维斯佩拉
  COORD_MARK: 0.5,           // 大坐标交点的小点
  /* 星系吸附粒度（单位：小格）。数据本来就是小格整数，保持 1 即可。 */
  COORD_SNAP_CELLS: 1,
  /* 比例尺：初始 0.5（视野较大，给以后加星系留空间），
     可缩到 0.25（约 136 小格高）、放到 1.45（小格 34px，能看到最小刻度） */
  ZOOM_MIN: 0.25,
  ZOOM_DEFAULT: 0.5,
  ZOOM_MAX: 1.45,
  SNAP: true,                // 暴露 window.SSS_COORD 给 starmap.js 对齐

  /* --- 配色沿用全站，便于激活区接口保持兼容（星图页不启用） --- */
  ACTIVE_STROKE: '#3a3072',
  DOT_COLOR: '#ffd700',
  BASE_STROKE: '#4a4a58',
  R: 30,
  STROKE: 1.8,

  /* --- 环境：保留风格，但整体压暗、静止 --- */
  AURORA: 0.18,
  AURA: 0,
  RING: 0,
  RAY: 0,
  CLICK_BURST: false,
  SKY_PARALLAX: 0.012,

  /* 星空：星图页不要背景星点（只有坐标纸与星系），
     STAR_DENSITY = 0 即完全不画星空层 */
  STAR_DENSITY: 0,
  STAR_TWINKLE: 0,

  /* 星图自身在逐帧重绘，背景保持完全静止：
     ANIM_FPS = 0 时不再起动画循环，也不会有整屏画布重绘去抢合成资源。 */
  ANIM_FPS: 0,

  /* 星图页不启用鼠标激活区 */
  INTERACTIVE: false
};
