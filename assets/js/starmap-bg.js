/* ============================================================
   星图页专用背景参数
   ------------------------------------------------------------
   星图页的背景是一张「坐标纸」：直角网格 + 网格交点，星系落在交点上。
   与全站六边形背景同一套配色（暗紫 / 冷灰 / 金色点缀），但结构完全不同，
   避免与星图的星点、光晕、连线互相干扰。

   · GRID_STYLE = 'coord'：换成直角坐标网格，格子边长 = 视口高 / COORD_N
     画布左上角即坐标原点，第 k 条线在 k*cell，星图按同一公式吸附
   · 网格线整体压暗，只有主线和坐标轴稍亮
   · 星空稀疏且静止，作为底噪
   · 极光只留一点点，且完全静止
   · 关闭鼠标激活区：星图自己的悬停/选中反馈才是主体

   必须在 assets/js/background.js 之前加载。
   ============================================================ */
window.SSS_BG = {
  /* --- 网格：坐标纸 --- */
  GRID_STYLE: 'coord',
  /* 纵向格数 34 → 基准格距 = 视口高 / 34 ≈ 21px；
     与缩放范围 [0.7, 1.45] 相乘后屏上格距保持在 15~30px，
     因此不需要任何限幅，网格步长恒等于 基准格距 × zoom，内容才能一直对齐。 */
  COORD_N: 34,
  COORD_MAJOR: 5,            // 每 5 格一条主线
  COORD_MINOR: '#1e1e2c',    // 细线：压得很暗，只提供结构感
  COORD_MAJOR_C: '#34344e',  // 主线
  COORD_AXIS: '#4a4a68',     // 坐标轴
  COORD_MARK: 0.5,           // 主线交点的小点
  SNAP: true,                // 暴露 window.SSS_COORD 给 starmap.js 对齐

  /* --- 配色沿用全站，便于激活区接口保持兼容（星图页不启用） --- */
  ACTIVE_STROKE: '#3a3072',
  DOT_COLOR: '#ffd700',
  BASE_STROKE: '#4a4a58',
  R: 30,
  STROKE: 1.8,

  /* --- 环境：保留风格，但整体压暗、静止 --- */
  AURORA: 0.18,
  AURA: 0,
  RING: 0,
  RAY: 0,
  CLICK_BURST: false,
  SKY_PARALLAX: 0.012,

  /* 星空：稀疏，作为网格之间的底噪 */
  STAR_DENSITY: 1 / 26000,
  STAR_TWINKLE: 0,

  /* 星图自身在逐帧重绘，背景保持完全静止：
     ANIM_FPS = 0 时不再起动画循环，也不会有整屏画布重绘去抢合成资源。 */
  ANIM_FPS: 0,

  /* 星图页不启用鼠标激活区 */
  INTERACTIVE: false
};
