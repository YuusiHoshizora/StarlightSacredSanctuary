/* ============================================================
   星图页专用背景参数
   ------------------------------------------------------------
   星图页的背景是一张「坐标纸」：直角网格 + 网格交点，星系落在交点上。
   与全站六边形背景同一套配色（暗紫 / 冷灰 / 金色点缀），但结构完全不同，
   避免与星图的星点、光晕、连线互相干扰。

   · GRID_STYLE = 'coord'：换成直角坐标网格，小格边长 = 视口高 / COORD_N
     画布左上角即坐标原点，第 k 条线在 k*小格，星图按同一公式吸附
   · 三级刻度：小坐标（每 1 小格）/ 中坐标（每 5 小格）/ 大坐标（每 25 小格）
     默认只画中、大坐标；小格间距够大（放大到一定比例尺）时小坐标才显现
   · 网格线整体压暗，三级之间靠颜色与线宽区分
   · 星空稀疏且静止，作为底噪
   · 极光只留一点点，且完全静止
   · 关闭鼠标激活区：星图自己的悬停/选中反馈才是主体

   必须在 assets/js/background.js 之前加载。
   ============================================================ */
window.SSS_BG = {
  /* --- 网格：坐标纸（三级刻度） --- */
  GRID_STYLE: 'coord',
  /* 纵向小格数 34 → 基准小格 = 视口高 / 34 ≈ 21px，
     与缩放范围 [0.7, 1.45] 相乘后屏上小格间距约 16~30px：
       · 中坐标（每 5 小格）= 83~172px   → 默认就可见
       · 大坐标（每 25 小格）= 415~858px → 默认就可见（约 5 个中格一个）
       · 小坐标（每 1 小格）默认太密，不画；放大到小格 ≥ 26px（约 zoom ≥ 1.1）才显现
     三级是固定比值，缩放时不会跳格；星点吸附在最小的那一级上。 */
  COORD_N: 34,
  COORD_MEDIUM_STEP: 5,      // 中坐标：每 5 个小格
  COORD_MAJOR_STEP: 25,      // 大坐标：每 5 个中格
  COORD_MINOR_MIN_PX: 26,    // 小坐标显现阈值（屏上小格间距，px）
  COORD_MEDIUM_MIN_PX: 18,   // 中坐标显现阈值
  COORD_MAJOR_MIN_PX: 60,    // 大坐标显现阈值
  COORD_MINOR: '#2b2b40',    // 小坐标：最细最暗
  COORD_MEDIUM_C: '#3b3b58', // 中坐标
  COORD_MAJOR_C: '#565679',  // 大坐标
  COORD_AXIS: '#6a6a92',     // 坐标轴
  COORD_MARK: 0.5,           // 大坐标交点的小点
  /* 星系吸附粒度（单位：小格）。1 = 落在小坐标格点上（星点只保证在小坐标上是整数格，
     在中/大坐标上不一定落在交点，这与坐标纸的用法一致）。 */
  COORD_SNAP_CELLS: 1,
  SNAP: true,                // 暴露 window.SSS_COORD 给 starmap.js 对齐

  /* --- 配色沿用全站，便于激活区接口保持兼容（星图页不启用） --- */
  ACTIVE_STROKE: '#3a3072',
  DOT_COLOR: '#ffd700',
  BASE_STROKE: '#4a4a58',
  R: 30,
  STROKE: 1.8,

  /* --- 环境：保留风格，但整体压暗、静止 --- */
  AURORA: 0.18,
  AURA: 0,
  RING: 0,
  RAY: 0,
  CLICK_BURST: false,
  SKY_PARALLAX: 0.012,

  /* 星空：稀疏，作为网格之间的底噪 */
  STAR_DENSITY: 1 / 26000,
  STAR_TWINKLE: 0,

  /* 星图自身在逐帧重绘，背景保持完全静止：
     ANIM_FPS = 0 时不再起动画循环，也不会有整屏画布重绘去抢合成资源。 */
  ANIM_FPS: 0,

  /* 星图页不启用鼠标激活区 */
  INTERACTIVE: false
};
